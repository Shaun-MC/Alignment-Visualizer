def _to_nested(column_major: dict, labels: tuple) -> dict:
    nested = {
        row: {col: column_major[col][i] for col in labels}
        for i, row in enumerate(labels)
    }
    for label in labels:
        nested["_"][label] = 0
        nested[label]["_"] = 0
    return nested


